#!/usr/bin/env bash
# Emit docs/CONFIG.md from Config.cpp's registerConfigValues().
#
# The table is GENERATED because the hand-written one drifted: the README this
# fork inherited documented `scale` as 0.5 and `workspace_gap` as 0 while the
# registered defaults were 0.82 and 40, and it listed six keys out of the
# seventy-nine that exist. A file nobody can forget to update beats a file
# somebody is asked to remember.
#
# The PARSE itself now lives in scripts/lib/configkeys.py, because Phase 11's
# settings schema mirrors the same registrations and a second copy of this regex
# is a second thing to forget. Two generators, one mirror.
#
#   scripts/gen_keys_table.sh          rewrite docs/CONFIG.md
#   scripts/gen_keys_table.sh --check  exit 1 if docs/CONFIG.md is out of date
#
# Run it from anywhere; paths are resolved against the repository root.
set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=$ROOT/docs/CONFIG.md

TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

PYTHONPATH=$ROOT/scripts/lib python3 - "$ROOT/Config.cpp" > "$TMP" <<'PY'
import sys
from configkeys import parse

keys = parse(sys.argv[1])

PREFIX = "plugin:hyprdrive:"
LEGACY_PREFIX = "plugin:scrolloverview:"
sections = {}
for k in keys:
    sections.setdefault(k.section, []).append(k)

TITLES = {"": "General", "input": "input", "dock": "dock", "shadow": "shadow"}
total = len(keys)

print("# Hyprdrive configuration keys")
print()
print("**Generated by `scripts/gen_keys_table.sh` from `Config.cpp`. Do not edit.**")
print("Regenerate after adding or changing a key; `--check` fails if this file is stale.")
print()
print(f"Every key lives under `{PREFIX}`. {total} keys.")
print()
print(f"**Compatibility.** The plugin was called `scrolloverview`; every key is")
print(f"also registered under the old `{LEGACY_PREFIX}` prefix and a value set")
print("there is copied onto the new name at config reload (the new name wins if")
print("both are set). The old spelling prints one deprecation warning per session")
print("and is removed one release after the rename.")
print()
# The four historical sections first, then any others in registration order
# (animation, motion_blur:<site>).
order = [s for s in ("", "input", "dock", "shadow") if s in sections] + [s for s in sections if s not in ("", "input", "dock", "shadow")]
for section in order:
    head = TITLES.get(section, section)
    print(f"## {head}" if not section else f"## `{section}`")
    print()
    print(f"Prefix: `{PREFIX}{section + ':' if section else ''}`")
    print()
    print("| key | type | default | range | description |")
    print("| --- | --- | --- | --- | --- |")
    for k in sections[section]:
        print(f"| `{k.name}` | {k.type} | `{k.default}` | {k.range} | {k.description} |")
    print()
PY

mkdir -p "$ROOT/docs"

if [ "${1:-}" = "--check" ]; then
    if ! diff -q "$TMP" "$OUT" >/dev/null 2>&1; then
        echo "docs/CONFIG.md is out of date -- run scripts/gen_keys_table.sh" >&2
        diff -u "$OUT" "$TMP" | head -40 >&2 || true
        exit 1
    fi
    echo "docs/CONFIG.md is current"
    exit 0
fi

cp "$TMP" "$OUT"
echo "wrote $OUT ($(grep -c '^| ' "$OUT") key rows)"
